    align = "l *{7}{S[table-format=-1.3]}",
    header = latex_header(names(table_6_latex))
  )

  table_7_average_correlations <- data.frame(
    Variable = rownames(results$tables$average_cross_country_correlations),
    results$tables$average_cross_country_correlations,
    row.names = NULL,
    check.names = FALSE
  )
  names(table_7_average_correlations)[names(table_7_average_correlations) == "mean"] <- "Mean"
  names(table_7_average_correlations)[names(table_7_average_correlations) == "usa_mean"] <- "USA Mean"

  write_table(
    table_7_average_correlations,
    "output/tables/table_7_average_cross_country_correlations.csv"
  )
  write_latex_tabular(
    table_7_average_correlations,
    "output/tables/table_7_average_cross_country_correlations.tex",
    align = "l *{11}{S[table-format=-1.3]}",
    header = latex_header(names(table_7_average_correlations))
  )
}

main()
