    table_6_us_correlations,
    "output/tables/table_6_us_correlations.csv"
  )
  table_6_latex <- table_6_us_correlations
  names(table_6_latex) <- c("Country", "y", "c", "x", "g", "nx", "n", "z")
  table_6_latex <- table_6_latex[table_6_latex$Country != "USA", ]
