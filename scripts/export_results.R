main <- function() {
  dir.create("output/tables", recursive = TRUE, showWarnings = FALSE)

  side_effect_files <- c(
    "output/figures/fraemployment.png",
    "output/figures/gbremployment.png",
    "output/figures/itaemployment.png"
  )

  on.exit(unlink(side_effect_files), add = TRUE)

  suppressWarnings(capture.output(source("R/main.R")))
  unlink(side_effect_files)

  write_table <- function(x, path) {
    write.csv(x, path, row.names = FALSE, na = "")
  }

  latex_escape <- function(x) {
    x <- gsub("\\\\", "\\\\textbackslash{}", x)
    x <- gsub("([#$%&_{}])", "\\\\\\1", x)
    x
  }

  latex_cell <- function(x) {
    if (length(x) == 0 || is.na(x) || identical(x, "")) {
      return("")
    }
    if (is.numeric(x)) {
      return(format(round(x, 3), trim = TRUE, scientific = FALSE))
    }
    text <- trimws(as.character(x))
    if (grepl("^[-+]?[0-9]*\\.?[0-9]+([eE][-+]?[0-9]+)?$", text)) {
      return(format(round(as.numeric(text), 3), trim = TRUE, scientific = FALSE))
    }
    latex_escape(gsub("-Q", ":", text, fixed = TRUE))
  }

  latex_row <- function(values) {
    paste(vapply(values, latex_cell, character(1)), collapse = " & ")
  }

  latex_header <- function(values, numeric_columns = seq_along(values)[-1]) {
    cells <- vapply(seq_along(values), function(i) {
      value <- latex_cell(values[[i]])
      if (i %in% numeric_columns) {
        paste0("\\multicolumn{1}{c}{", value, "}")
      } else {
        value
      }
    }, character(1))
    paste(cells, collapse = " & ")
  }

  write_latex_tabular <- function(data, path, align = NULL, header = NULL) {
    if (is.null(align)) {
      align <- paste0("l", paste(rep("c", ncol(data) - 1), collapse = ""))
    }

    header_row <- if (is.null(header)) {
      latex_header(names(data), numeric_columns = integer(0))
    } else {
      header
    }

    rows <- apply(data, 1, latex_row)
    table_body <- c(
      paste0("\\begin{tabular}{", align, "}"),
      "\\toprule",
      paste0(header_row, " \\\\"),
      "\\midrule",
      paste0(rows, " \\\\"),
      "\\bottomrule",
      "\\end{tabular}"
    )

    writeLines(
      c(
        "% Generated by scripts/export_results.R. Do not edit by hand.",
        table_body
      ),
      path
    )
  }

  write_timespan_latex <- function(data, path) {
    table <- data
    names(table) <- c(
      "Country",
      "GDP Last", "GDP First",
      "Consumption Last", "Consumption First",
      "Investment Last", "Investment First",
      "Government Last", "Government First",
      "Net Exports Last", "Net Exports First",
      "Employment Last", "Employment First"
    )
    write_latex_tabular(
      table,
      path,
      align = "l *{12}{c}",
      header = latex_header(names(table), numeric_columns = integer(0))
    )
  }

  legacy_timespan_table <- function(variable_results) {
    timespan_without_country <- function(timespan) {
      timespan[c("last_observation", "first_observation")]
    }

    timespan <- data.frame(
      variable_results$gdp$timespan,
      timespan_without_country(variable_results$consumption$timespan),
      timespan_without_country(variable_results$investment$timespan),
      timespan_without_country(variable_results$government$timespan),
      timespan_without_country(variable_results$net_exports$timespan),
      check.names = FALSE
    )
    names(timespan)[names(timespan) == "country"] <- "Country"
    employment_timespan <- variable_results$employment$timespan
    names(employment_timespan) <- c("Country", "Last Observation", "First Observation")
    table <- suppressWarnings(
      merge(timespan, employment_timespan, by = "Country", all = TRUE)
    )
    names(table) <- c(
      "Country",
      rep(c("Last Observation.x", "First Observation.x"), 5),
      "Last Observation.y",
      "First Observation.y"
    )
    table
  }

  write_table_with_key <- function(x, key, path) {
    key_column <- data.frame(row_key = rownames(x), row.names = NULL, check.names = FALSE)
    names(key_column) <- key
    x <- data.frame(key_column, x, check.names = FALSE)
    write_table(x, path)
  }

