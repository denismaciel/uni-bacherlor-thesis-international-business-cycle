main <- function() {
  dir.create("output/tables", recursive = TRUE, showWarnings = FALSE)

  side_effect_files <- c(
    "output/figures/fraemployment.png",
    "output/figures/gbremployment.png",
    "output/figures/itaemployment.png"
  )

  on.exit(unlink(side_effect_files), add = TRUE)

  suppressWarnings(capture.output(source("R/main.R")))
  unlink(side_effect_files)

  write_table <- function(x, path) {
    write.csv(x, path, row.names = FALSE, na = "")
  }

  latex_escape <- function(x) {
    x <- gsub("\\\\", "\\\\textbackslash{}", x)
    x <- gsub("([#$%&_{}])", "\\\\\\1", x)
    x
  }

  latex_cell <- function(x) {
    if (length(x) == 0 || is.na(x) || identical(x, "")) {
      return("")
    }
    if (is.numeric(x)) {
      return(format(round(x, 3), trim = TRUE, scientific = FALSE))
    }
    text <- trimws(as.character(x))
    if (grepl("^[-+]?[0-9]*\\.?[0-9]+([eE][-+]?[0-9]+)?$", text)) {
      return(format(round(as.numeric(text), 3), trim = TRUE, scientific = FALSE))
    }
    latex_escape(gsub("-Q", ":", text, fixed = TRUE))
  }

  latex_row <- function(values) {
    paste(vapply(values, latex_cell, character(1)), collapse = " & ")
  }

  write_latex_table <- function(data, path, caption, label, align = NULL, resize = FALSE, header = NULL) {
    if (is.null(align)) {
      align <- paste0("l", paste(rep("c", ncol(data) - 1), collapse = ""))
    }

    header_row <- if (is.null(header)) {
      latex_row(names(data))
    } else {
      header
    }

    rows <- apply(data, 1, latex_row)
    table_body <- c(
      paste0("\\begin{tabular}{", align, "}"),
      "\\hline\\hline",
      paste0(header_row, " \\\\"),
      "\\hline",
      paste0(rows, " \\\\"),
      "\\hline",
      "\\end{tabular}"
    )

    if (resize) {
      table_body <- c(
        "\\resizebox{\\textwidth}{!}{%",
        table_body,
        "}"
      )
    }

    writeLines(
      c(
        "% Generated by scripts/export_results.R. Do not edit by hand.",
        "\\begin{table}[htbp]",
        "\\centering",
        table_body,
        paste0("\\caption{", caption, "\\label{", label, "}}"),
        "\\end{table}"
      ),
      path
    )
  }

  write_timespan_latex <- function(data, path) {
    table <- data
    names(table) <- c(
      "Country",
      "GDP Last", "GDP First",
      "Consumption Last", "Consumption First",
      "Investment Last", "Investment First",
      "Government Last", "Government First",
      "Net Exports Last", "Net Exports First",
      "Employment Last", "Employment First"
    )
    write_latex_table(
      table,
      path,
      "Length of the Time Series for each Country",
      "tab:timespan",
      resize = TRUE
    )
  }

  write_table_with_key <- function(x, key, path) {
    key_column <- data.frame(row_key = rownames(x), row.names = NULL, check.names = FALSE)
    names(key_column) <- key
    x <- data.frame(key_column, x, check.names = FALSE)
    write_table(x, path)
  }

  write_table(
    results$tables$timespan,
    "output/tables/table_3_timespan.csv"
  )
  write_timespan_latex(
    results$tables$timespan,
    "output/tables/table_3_timespan.tex"
  )

  write_table(
    results$tables$standard_deviations,
    "output/tables/table_4_standard_deviations.csv"
  )
  write_latex_table(
    results$tables$standard_deviations,
    "output/tables/table_4_standard_deviations.tex",
    "Standard Deviations",
    "tab:stdv",
    resize = TRUE
  )

  write_table(
    results$tables$within_country_correlations,
    "output/tables/table_5_within_country_correlations.csv"
  )
  write_latex_table(
    results$tables$within_country_correlations,
    "output/tables/table_5_within_country_correlations.tex",
    "Within-country Correlation between Output and other Variables",
    "tab:corrwithin",
    resize = TRUE
  )

  table_6_us_correlations <- results$tables$usa_correlation_matrix
  names(table_6_us_correlations) <- c(
    "Row.names",
    "usa.gdpcor",
    "usa.concor",
    "usa.invcor",
    "usa.govcor",
    "usa.netcor",
    "usa.empcor",
    "usa.solcor"
  )

  write_table(
    table_6_us_correlations,
    "output/tables/table_6_us_correlations.csv"
  )
  table_6_latex <- table_6_us_correlations
  names(table_6_latex) <- c("Country", "y", "c", "x", "g", "nx", "n", "z")
  table_6_latex <- table_6_latex[table_6_latex$Country != "USA", ]
  write_latex_table(
    table_6_latex,
    "output/tables/table_6_us_correlations.tex",
    "Cross-country Correlations",
    "tab:corusa",
    resize = TRUE
  )

  table_7_average_correlations <- data.frame(
    Variable = rownames(results$tables$average_cross_country_correlations),
    results$tables$average_cross_country_correlations,
    row.names = NULL,
    check.names = FALSE
  )

  write_table_with_key(
    results$tables$average_cross_country_correlations,
    "Variable",
    "output/tables/table_7_average_cross_country_correlations.csv"
  )
  write_latex_table(
    table_7_average_correlations,
    "output/tables/table_7_average_cross_country_correlations.tex",
    "Average Cross-country Correlation among all Countries",
    "tab:avgcor",
    resize = TRUE
  )
}

main()
